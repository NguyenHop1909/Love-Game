-- Replace legacy permissive policies on the application's own tables.
do $$ declare t text; p record; begin
  foreach t in array array['love_members','quizzes','rewards_penalties','wheel_settings','user_inventory','audit_logs','love_operations','couple_entries'] loop
    execute format('alter table public.%I enable row level security', t);
    for p in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
      execute format('drop policy %I on public.%I', p.policyname, t);
    end loop;
    execute format('revoke all on public.%I from anon, authenticated', t);
    if t <> 'love_operations' then
      execute format('grant select on public.%I to authenticated', t);
      execute format('create policy members_read on public.%I for select to authenticated using (public.love_role() is not null)', t);
    end if;
  end loop;
end $$;

