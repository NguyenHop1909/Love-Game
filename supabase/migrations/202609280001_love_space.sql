create or replace function public.love_validate_settings() returns trigger language plpgsql set search_path = '' as $$
begin
  if new.spin_cost is null or new.spin_cost < 0 or new.free_spins is null or new.free_spins < 0
    or jsonb_typeof(new.prizes::jsonb) <> 'array' or jsonb_array_length(new.prizes::jsonb) not between 1 and 20 then
    raise exception 'Cấu hình vòng quay không hợp lệ.';
  end if;
  if exists(select 1 from jsonb_array_elements(new.prizes::jsonb) p where coalesce(length(trim(p->>'text')),0) not between 1 and 100) then
    raise exception 'Tên quà phải có từ 1 đến 100 ký tự.';
  end if;
  return new;
end $$;
