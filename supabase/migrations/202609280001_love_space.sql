create or replace function public.love_redeem(p_request_id uuid, p_kind text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare saved public.love_operations; cfg public.wheel_settings; amount bigint; cost integer;
  prize text; idx integer; result jsonb; gift_id text;
begin
  if public.love_role() is distinct from 'user' then raise exception 'Chỉ người nhận quà được đổi phiếu.'; end if;
  if p_request_id is null or p_kind is null or p_kind not in ('HUN_MOI','HUN_SAU','SPIN','FREE_SPIN') then raise exception 'Yêu cầu không hợp lệ.'; end if;
  perform pg_advisory_xact_lock(20260928);
  select * into saved from public.love_operations where request_id = p_request_id;
  if found then
    if saved.user_id <> auth.uid() or saved.kind <> p_kind then raise exception 'Mã giao dịch đã được sử dụng.'; end if;
    return saved.result;
  end if;
  select * into cfg from public.wheel_settings where id = 1 for update;
  if not found then raise exception 'Chưa có cấu hình vòng quay.'; end if;
  if p_kind in ('SPIN','FREE_SPIN') then
    if jsonb_array_length(cfg.prizes::jsonb) < 1 then raise exception 'Vòng quay chưa có quà.'; end if;
    if p_kind = 'FREE_SPIN' and cfg.free_spins <= 0 then raise exception 'Đã hết lượt miễn phí.'; end if;
    idx := floor(random() * jsonb_array_length(cfg.prizes::jsonb));
    prize := cfg.prizes::jsonb->idx->>'text';
    cost := case when p_kind = 'FREE_SPIN' then 0 else cfg.spin_cost end;
  else
    cost := case when p_kind = 'HUN_MOI' then 10 else 50 end;
    prize := case when p_kind = 'HUN_MOI' then 'Một cái hun môi 💋' else 'Một cái hun sâu 💕' end;
  end if;
  if cost is null or cost < 0 then raise exception 'Chi phí không hợp lệ.'; end if;
  select coalesce(sum(coalesce(reward_amount,0) - coalesce(penalty_amount,0)),0) into amount from public.rewards_penalties;
  if cost > 0 and amount < cost then raise exception 'Không đủ phiếu để đổi quà.'; end if;
  if p_kind = 'FREE_SPIN' then
    update public.wheel_settings set free_spins = free_spins - 1 where id = 1;
  end if;
  if cost > 0 then
    insert into public.rewards_penalties(date, reward_amount, penalty_amount, reward_reason)
    values ((now() at time zone 'Asia/Ho_Chi_Minh')::date, -cost, 0, 'Đổi quà: ' || prize);
  end if;
  insert into public.user_inventory(prize_text,status) values (prize,'Chưa sử dụng') returning id::text into gift_id;
  result := jsonb_build_object('gift_id',gift_id,'prize',prize,'index',idx,'prizes',cfg.prizes,'cost',cost,'balance',amount-cost);
  insert into public.love_operations(request_id,user_id,kind,result) values(p_request_id,auth.uid(),p_kind,result);
  return result;
end $$;

create or replace function public.love_gift_action(p_id text, p_action text, p_date date default null) returns void
language plpgsql security definer set search_path = '' as $$
declare gift public.user_inventory; who text := public.love_role();
begin
  if who is null then raise exception 'Bạn chưa có quyền truy cập.'; end if;
  select * into gift from public.user_inventory where id::text = p_id for update;
  if not found then raise exception 'Không tìm thấy quà.'; end if;
  if p_action = 'request' and who = 'user' and gift.status = 'Chưa sử dụng' then
    update public.user_inventory set status = 'Chờ hẹn' where id::text = p_id;
  elsif p_action = 'cancel' and who = 'user' and gift.status = 'Chờ hẹn' then
    update public.user_inventory set status = 'Chưa sử dụng', scheduled_for = null where id::text = p_id;
  elsif p_action = 'schedule' and who = 'admin' and gift.status in ('Chờ hẹn','Đã hẹn') and p_date >= (now() at time zone 'Asia/Ho_Chi_Minh')::date then
    update public.user_inventory set status = 'Đã hẹn', scheduled_for = p_date where id::text = p_id;
  elsif p_action = 'complete' and who = 'admin' and gift.status = 'Đã hẹn' then
    update public.user_inventory set status = 'Đã sử dụng' where id::text = p_id;
  elsif p_action = 'revoke' and who = 'admin' and gift.status <> 'Đã sử dụng' then
    update public.user_inventory set status = 'Đã thu hồi' where id::text = p_id;
  else raise exception 'Trạng thái đã thay đổi hoặc thao tác không hợp lệ.';
  end if;
end $$;

create or replace function public.love_entry_toggle(p_id uuid, p_action text) returns void
language plpgsql security definer set search_path = '' as $$
declare entry public.couple_entries; current_ids uuid[];
begin
  if public.love_role() is null then raise exception 'Bạn chưa có quyền truy cập.'; end if;
  select * into entry from public.couple_entries where id = p_id for update;
  if not found then raise exception 'Mục này đã bị xóa.'; end if;
  if p_action = 'like' and entry.kind = 'date' then
    current_ids := entry.liked_by;
    update public.couple_entries set liked_by = case when auth.uid() = any(current_ids) then array_remove(current_ids,auth.uid()) else array_append(current_ids,auth.uid()) end where id = p_id;
  elsif p_action = 'done' and entry.kind = 'mission' then
    current_ids := entry.done_by;
    update public.couple_entries set done_by = case when auth.uid() = any(current_ids) then array_remove(current_ids,auth.uid()) else array_append(current_ids,auth.uid()) end where id = p_id;
  else raise exception 'Thao tác không hợp lệ.'; end if;
end $$;

create or replace function public.love_submit_quiz(p_id text, p_score integer, p_proof_path text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if public.love_role() is distinct from 'user' then raise exception 'Bạn không được nộp bài.'; end if;
  if p_score is null or p_score < 0 or p_proof_path is null or p_proof_path not like auth.uid()::text || '/%' then raise exception 'Điểm hoặc ảnh không hợp lệ.'; end if;
  if not exists(select 1 from storage.objects where bucket_id = 'quiz-images' and name = p_proof_path) then raise exception 'Chưa tải ảnh lên.'; end if;
  update public.quizzes set score = p_score, proof_path = p_proof_path, status = 'COMPLETED' where id::text = p_id and status = 'PENDING';
  if not found then raise exception 'Bài đã được nộp hoặc đã bị xóa.'; end if;
end $$;

